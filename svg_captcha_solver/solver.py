"""
Core solver implementation for SVG Captchas.
"""

from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Optional, Tuple, Union
import difflib

from .models import CHAR_MAP, AMBIGUOUS_PATTERNS
from .parser import PathElement, parse_svg


@dataclass
class CharRecognition:
    char: str
    confidence: float
    bbox: Tuple[float, float, float, float]
    pattern: str
    exact_match: bool


@dataclass
class SolveResult:
    text: str
    characters: List[CharRecognition]

    def __str__(self) -> str:
        return self.text


class SvgCaptchaSolver:
    """
    Fast, lightweight SVG CAPTCHA solver using vector path analysis.
    Optimized for captchas generated by svg-captcha, @depup/svg-captcha,
    and other tools using Comismsh.ttf or compatible font glyphs.
    """

    def __init__(self, custom_model: Optional[Dict[str, str]] = None):
        """
        Initialize solver with optional custom pattern-to-character mapping.
        """
        self.model: Dict[str, str] = dict(CHAR_MAP)
        if custom_model:
            self.model.update(custom_model)
        self.ambiguous_patterns = AMBIGUOUS_PATTERNS

    def _match_pattern(self, element: PathElement) -> Tuple[str, float, bool]:
        """
        Match a PathElement's command pattern against the known dictionary.
        Returns: (char, confidence, is_exact)
        """
        pat = element.pattern
        if pat in self.model:
            # Check if this pattern has disambiguation logic (e.g., 'I' vs 'l')
            if pat in self.ambiguous_patterns:
                rule = self.ambiguous_patterns[pat]
                char = rule['disambiguate'](element.bbox)
                return char, 1.0, True
            return self.model[pat], 1.0, True

        # Fallback: fuzzy match using SequenceMatcher on command string
        best_match = '?'
        best_ratio = 0.0
        for known_pat, char in self.model.items():
            ratio = difflib.SequenceMatcher(None, pat, known_pat).ratio()
            if ratio > best_ratio:
                best_ratio = ratio
                best_match = char

        if best_ratio >= 0.85:
            return best_match, round(best_ratio, 3), False

        return '?', 0.0, False

    def analyze(self, svg_content: str) -> SolveResult:
        """
        Analyze the SVG and return structured recognition results
        including character positions and confidence scores.
        """
        path_elements = parse_svg(svg_content)
        characters: List[CharRecognition] = []

        for p in path_elements:
            char, conf, exact = self._match_pattern(p)
            characters.append(
                CharRecognition(
                    char=char,
                    confidence=conf,
                    bbox=p.bbox,
                    pattern=p.pattern,
                    exact_match=exact
                )
            )

        text = "".join(c.char for c in characters)
        return SolveResult(text=text, characters=characters)

    def solve(self, svg_content: str) -> str:
        """
        Solve an SVG CAPTCHA from its SVG markup string.
        """
        result = self.analyze(svg_content)
        return result.text

    def solve_file(self, file_path: Union[str, Path]) -> str:
        """
        Solve an SVG CAPTCHA from a file path.
        """
        path = Path(file_path)
        with open(path, "r", encoding="utf-8", errors="ignore") as f:
            content = f.read()
        return self.solve(content)


# Default module-level instance for convenience
_default_solver = SvgCaptchaSolver()

def solve(svg_content: str) -> str:
    """Convenience function to solve an SVG CAPTCHA string."""
    return _default_solver.solve(svg_content)

def solve_file(file_path: Union[str, Path]) -> str:
    """Convenience function to solve an SVG CAPTCHA file."""
    return _default_solver.solve_file(file_path)
